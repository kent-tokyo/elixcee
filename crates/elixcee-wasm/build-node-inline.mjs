#!/usr/bin/env node
// Post-processes wasm-pack's `--target nodejs` output (pkg-node/, produced by build.sh)
// into a single self-contained CommonJS module that inlines the compiled .wasm bytes,
// exactly mirroring what build-browser-inline.mjs already does for the `--target web`
// output. Same technique, different base64 decoder (`Buffer.from` here, `atob` there) and
// different module format (CJS here, ESM there).
//
// Why this exists: wasm-pack's generated nodejs glue ends with
//
//     const wasmPath = `${__dirname}/elixcee_wasm_bg.wasm`;
//     const wasmBytes = require('fs').readFileSync(wasmPath);
//
// which is BUNDLE-OUTPUT-relative, not source-relative, the moment a consumer bundles this
// package. Two real consumer failures followed from that, both previously disclosed in
// packages/xlsx/scripts/wasm-smoke.mjs's header and ROADMAP.md rather than fixed:
//   - bundling to ESM crashes outright with `__dirname is not defined` (a ReferenceError at
//     module scope, not a recoverable error);
//   - bundling to CJS "works" only if the consumer manually copies elixcee_wasm_bg.wasm
//     next to their bundle output — a step no normal npm consumer expects to perform.
// Inlining the bytes removes the filesystem lookup entirely, so both work with no consumer
// action. Neither the synchronous `read()` contract nor the no-top-level-await constraint
// changes: `new WebAssembly.Module(bytes)` below is the same synchronous call wasm-pack
// already emitted, just fed from an in-module constant instead of from disk.
//
// This script is invoked BY build.sh, so a fresh `bash build.sh` regenerates the inlined
// loader from scratch — nothing here hand-patches wasm-pack's generated output, and no edit
// to it can be silently lost on the next rebuild. Like build-browser-inline.mjs, it hard-
// fails if wasm-pack's generated shape stops matching the anchor below rather than emitting
// a silently-wrong file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const glue = readFileSync(join(here, 'pkg-node/elixcee_wasm.js'), 'utf8');
const wasmBytes = readFileSync(join(here, 'pkg-node/elixcee_wasm_bg.wasm'));
const b64 = wasmBytes.toString('base64');

// The two-line filesystem lookup wasm-pack generates. Anchored as an exact string (not a
// loose regex) for the same reason build-browser-inline.mjs anchors on its EXPORT_LINE: if
// wasm-pack's output shape changes, this must fail loudly at build time, not quietly
// produce a loader that still reads from disk.
const FS_LOOKUP = [
  'const wasmPath = `${__dirname}/elixcee_wasm_bg.wasm`;',
  "const wasmBytes = require('fs').readFileSync(wasmPath);",
].join('\n');

if (!glue.includes(FS_LOOKUP)) {
  throw new Error(
    `build-node-inline.mjs: expected wasm-pack's --target nodejs output to contain the ` +
      `block ${JSON.stringify(FS_LOOKUP)} — its generated glue shape changed; update this ` +
      `script's FS_LOOKUP to match before trusting the output.`
  );
}

// Buffer, not atob: this is the Node-only entry point (index.cjs already uses Buffer in its
// own toBytes), and Buffer.from is materially faster than a per-char atob loop for a
// ~350KB payload decoded on every process start. The browser build keeps atob for the
// opposite reason — no Buffer there.
const out = glue.replace(
  FS_LOOKUP,
  `// ---- inlined node init (generated by build-node-inline.mjs; do not hand-edit) ----
// Inlined rather than read from a sibling .wasm file so that bundling this package (to
// either CJS or ESM) needs no __dirname, no asset-copy step, and no bundler asset loader.
const ELIXCEE_WASM_BASE64 = '${b64}';
const wasmBytes = Buffer.from(ELIXCEE_WASM_BASE64, 'base64');`
);

const outPath = join(here, 'pkg-node/elixcee_wasm.inline.cjs');
writeFileSync(outPath, out);
console.log(
  `wrote ${outPath} (${out.length} bytes; wasm payload ${wasmBytes.length} bytes / ${b64.length} base64 chars)`
);
