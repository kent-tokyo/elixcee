#!/usr/bin/env node
// Post-processes wasm-pack's `--target web` output (pkg-web/, produced by build.sh) into a
// single self-contained ESM module that inlines the compiled .wasm bytes and calls
// wasm-bindgen's own `initSync` synchronously at import time, instead of the default
// `__wbg_init` (async, fetch-based) export wasm-pack generates.
//
// Why: see docs/xlsx-architecture.md's "Phase 2B-0: sync WASM/read() bridge feasibility".
// Two things ruled out the obvious alternatives — bundlers don't resolve a bare `.wasm`
// import by default (confirmed: esbuild fails on it with default settings), and the
// browser has no `fs` module, so the `--target nodejs` approach (readFileSync a sibling
// .wasm file) doesn't apply here. Inlining the bytes as base64 and decoding them
// synchronously sidesteps both. The try/catch around the synchronous compile call turns a
// blocked-CSP CompileError (missing 'wasm-unsafe-eval') or a size-limit RangeError (the
// unverified-but-possible Safari claim from 2B-0) into one clearly-coded, documented
// error instead of an opaque unhandled exception.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const glue = readFileSync(join(here, 'pkg-web/elixcee_wasm.js'), 'utf8');
const wasmBytes = readFileSync(join(here, 'pkg-web/elixcee_wasm_bg.wasm'));
const b64 = wasmBytes.toString('base64');

// The generated glue's own default export (`__wbg_init`, async + fetch-based) and the
// bare `initSync` export are both replaced below with our own synchronous init + a
// narrower re-export — everything ABOVE that line (readWorkbook, initSync itself, the
// low-level wasm-bindgen plumbing) is kept verbatim.
const EXPORT_LINE = 'export { initSync, __wbg_init as default };';
if (!glue.includes(EXPORT_LINE)) {
  throw new Error(
    `build-browser-inline.mjs: expected wasm-pack's --target web output to end with the ` +
    `line ${JSON.stringify(EXPORT_LINE)} — its generated glue shape changed; update this ` +
    `script's EXPORT_LINE to match before trusting the output.`
  );
}
const body = glue.replace(EXPORT_LINE, '');

const out = `${body}
// ---- inlined browser init (generated by build-browser-inline.mjs; do not hand-edit) ----
const ELIXCEE_WASM_BASE64 = '${b64}';

function base64ToBytes(b64str) {
  const bin = atob(b64str);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; ++i) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

try {
  initSync({ module: base64ToBytes(ELIXCEE_WASM_BASE64) });
} catch (e) {
  const err = new Error(
    'elixcee-wasm: synchronous WebAssembly compile failed in this browser environment. ' +
    'Likely a Content-Security-Policy blocking \\'wasm-unsafe-eval\\', or (unconfirmed, ' +
    'see docs/xlsx-architecture.md) a browser-enforced size limit on synchronous ' +
    'compilation. Original error: ' + e.message
  );
  err.cause = e;
  err.code = 'ELIXCEE_WASM_SYNC_COMPILE_FAILED';
  throw err;
}
// readWorkbook is already exported inline above (wasm-pack emits
// \`export function readWorkbook(...)\`) — nothing left to re-export here.
`;

const outPath = join(here, 'pkg-web/elixcee_wasm.inline.mjs');
writeFileSync(outPath, out);
console.log(
  `wrote ${outPath} (${out.length} bytes; wasm payload ${wasmBytes.length} bytes / ${b64.length} base64 chars)`
);
